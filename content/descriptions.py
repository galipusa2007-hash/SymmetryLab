def describe(molecule, operation):
    info = MOLECULE_CONTEXT[molecule.name]
    if operation.kind == 'identity':
        math = 'r′ = I · r = r. Матрица E единичная; угол и координаты не изменяются.'
    elif operation.kind == 'rotation':
        math = f'r′ = R · r. Вращение на {operation.angle:g}° вокруг показанной оси; det(R) = +1.'
    elif operation.kind == 'reflection':
        math = 'r′ = (I − 2nnᵀ) · r, где n — единичная нормаль к плоскости; det = −1.'
    elif operation.kind == 'improper':
        math = f'r′ = M · R · r. Сначала поворот на {operation.angle:g}°, затем отражение; det = −1.'
    else:
        math = 'r′ = −r.'
    movement = TYPE_TEXT[operation.kind]
    chemistry = info['chemistry'] + ' Одна операция не вызывает химического изменения: это способ обнаружить ограничения, налагаемые симметрией на свойства.'
    return {'math': math, 'movement': movement, 'chemistry': chemistry}
